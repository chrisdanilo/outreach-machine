#!/usr/bin/env python3
"""Render the TLP dashboard. One script, one output line.

THE UNIT IS THE ORGANISATION. Chris, 2026-09-02.
THE DASHBOARD GATHERS AND PRESENTS. Chris, 2026-09-28. It does not track posting to TLBS.

Owners -- a number has exactly one:
  counted   TLP/dashboard-data.json, one block per quarter.  A judgment call; no script derives it.
  funnel    funnel-conversion.json.                          Generated by funnel_conversion.py.
  computed  nobody -- recomputed in the browser.             Percentages, the quarter clock, which
                                                             quarter is current, what moved.

Reads   TLP/dashboard-data.json, funnel-conversion.json
Writes  runs/<date>/dashboard_seed.json          the assembled data block, for the run record
        TLP/tlp-practice-dashboard.html          ONLY the <script id="data"> block is replaced. One
                                                 page: the current quarter in full, then one line per
                                                 quarter in sequence (Chris, 2026-10-01)
        TLP/TLP-<quarter>.md                     a generated, read-only view of EACH counted block

It RENDERS. It never RECOUNTS and never advances counted_through -- that is a refresh session's job.
Exit 1 and print PROBLEM when the page could show a figure that is not the counted record.
"""
import json, pathlib, re, sys, datetime, os, time
os.environ.setdefault("TZ", "America/Denver")
try:
    time.tzset()
except Exception:
    pass

HST    = pathlib.Path(__file__).resolve().parents[3]
TLP    = HST / "TLP"
DATA   = TLP / "dashboard-data.json"
HTML   = TLP / "tlp-practice-dashboard.html"
FUNNEL = HST / "Marketing" / "outreach-machine" / "funnel-conversion.json"
RUNS   = HST / "Marketing" / "outreach-machine" / "runs"

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import counted_record as CR


def pct(n, d, places=1):
    if n is None or not d:
        return None
    v = round(n / d * 100 + 1e-9, places)
    return int(v) if v == int(v) else v


def fmt_pct(p):
    return "—" if p is None else f"{p}%"


def nice_date(s):
    d = datetime.date.fromisoformat(s)
    return f"{d.day} {d.strftime('%b')}"


def funnel_view(F):
    """The five bands the page draws, plus the sentences under them. Numbers come straight from
    funnel-conversion.json; nothing is recomputed except display percentages."""
    n  = F["orgs_contacted"]
    ap, mt, pr, sl = F["approaches"], F["meetings"], F["proposals"], F["sales"]
    stages = [
        {"name": "Contacted",      "value": n,           "sub": f"{F['emails_sent']['total']} emails"},
        {"name": "Approaches",     "value": ap["orgs"],  "sub": "replied"},
        {"name": "Meetings held",  "value": mt["held"],  "sub": (f"{mt['booked']} booked" if mt.get("booked") else "")},
        {"name": "Proposals",      "value": pr["total"], "sub": f"{pr['after_meeting']} after a meeting"},
        {"name": "Sales",          "value": sl["total"], "sub": f"USD {sl['value']:,}", "display": f"{sl['total']}"},
    ]
    ratio = lambda x: f"1 in {round(n / x)}" if x else "—"
    ratios = (f"{ratio(ap['orgs'])} organisations contacted produces an Approach, {ratio(mt['held'])} a Meeting held, "
              f"{ratio(pr['total'])} a Proposal.")
    parts = []
    for fld in ("Approaches", "Meetings", "Proposals"):
        s = F.get("scope", {}).get(fld)
        if s and s.get("counted") is not None and s["campaign"] != s["counted"]:
            parts.append(f"{fld} {s['campaign']} of the {s['counted']} counted (not cold outreach: {'; '.join(s['non_campaign'])})")
    scope = ("Scope — " + " · ".join(parts) + ".") if parts else ""
    problems = []
    if F.get("scope_errors"):
        problems.append("scope does not reconcile: " + "; ".join(F["scope_errors"]))
    if ap.get("not_in_send_ledger"):
        problems.append(f"{len(ap['not_in_send_ledger'])} organisations replied but have no send row in contacted.jsonl "
                        f"({', '.join(ap['not_in_send_ledger'])}). Counted as Approaches; the outreach run needs to reconcile them.")
    if F.get("unattributed"):
        problems.append("replies not yet attributed to an email: " + ", ".join(F["unattributed"]))
    return {
        "floor": nice_date(F["floor"]), "generated": F["generated"], "stages": stages,
        "ratios": ratios, "scope": scope, "problem": " ".join(problems) if problems else None,
        "counted_approaches": F.get("approaches", {}).get("counted"),
    }, problems


def carried_line(c):
    """targets_carried is either true (every target carried) or a list of the fields still carried."""
    if not c:
        return ""
    if isinstance(c, list):
        return f" · targets carried from the previous quarter, unconfirmed: {', '.join(c)}"
    return " · targets carried from the previous quarter, unconfirmed"


def quarter_markdown(d, q):
    """A read-only Obsidian view of one quarter block. Generated; never hand-edited."""
    FIELDS, MONEY = d["fields"], set(d.get("money", []))
    money = lambda v: "—" if v is None else f"USD {v:,}"
    val   = lambda f, v: "—" if v is None else (money(v) if f in MONEY else str(v))
    L = []
    A = L.append
    A("---")
    A(f"business: Human Skills Training")
    A(f"type: generated-view")
    A(f"title: \"TLP Practice — {q['label']}\"")
    A(f"quarter: {q['id']}")
    A(f"status: {q['status']}")
    A(f"counted-through: {q.get('counted_through') or 'not yet counted'}")
    A(f"generated: {d['generated']}")
    A("tags: [TLP, dashboard, practice-metrics, generated]")
    A("---")
    A("")
    A(f"# TLP Practice — {q['label']}")
    A("")
    A("> **GENERATED by `Marketing/outreach-machine/bin/dashboard_seed.py` from `dashboard-data.json` — do not hand-edit.** "
      "Rules in `TLP-Rules.md`. The published dashboard is the canonical display.")
    A("")
    A(f"{q['start']} → {q['end']} · counted in {d.get('unit', 'organisations')} · counted through **{q.get('counted_through') or '—'}**"
      + carried_line(q.get("targets_carried")))
    A("")
    A("| Field | Quarter to date | Target | % |")
    A("| --- | --- | --- | --- |")
    for f in FIELDS:
        v, t = q["fields"].get(f), q["targets"].get(f)
        A(f"| {f} | **{val(f, v)}** | {val(f, t)} | {fmt_pct(pct(v, t))} |")
    if q.get("clusters"):
        A("")
        A("## Cluster targets")
        A("")
        if q.get("clusters_note"):
            A(f"> {q['clusters_note']}")
            A("")
        A("| Cluster | Price | Sales (units) | Sales | Meetings | Approaches |")
        A("| --- | --- | --- | --- | --- | --- |")
        tot = {"units": 0, "Sales": 0, "Meetings": 0, "Approaches": 0}
        for c in q["clusters"]:
            ct = c["targets"]
            A(f"| {c['id']} – {c['name']} | {money(c['price'])} | {c.get('sales_units', '—')} | {val('Sales', ct.get('Sales'))} | "
              f"{val('Meetings', ct.get('Meetings'))} | {val('Approaches', ct.get('Approaches'))} |")
            tot["units"] += c.get("sales_units") or 0
            for f in ("Sales", "Meetings", "Approaches"):
                tot[f] += ct.get(f) or 0
        A(f"| **Practice total** | | **{tot['units']}** | **{money(tot['Sales'])}** | **{tot['Meetings']}** | **{tot['Approaches']}** |")
    if q.get("calls"):
        A("")
        A("## Needs Chris's call")
        A("")
        A("| # | Field | Question | Effect on the number |")
        A("| --- | --- | --- | --- |")
        for c in q["calls"]:
            A(f"| {c['id']} | {c['field']}{' (' + c['kind'] + ')' if c.get('kind') else ''} | {c['question']} | {c.get('effect', '')} |")
    R = q.get("records", {})
    def table(title, items, head, row):
        if not items:
            return
        A(""); A(f"## {title} — {len(items)}"); A("")
        A("| " + " | ".join(head) + " |"); A("|" + " --- |" * len(head))
        for r in sorted(items, key=lambda r: r["date"]):
            A("| " + " | ".join(str(x).replace("|", "/") for x in row(r)) + " |")
    table("Approaches", R.get("approaches"), ["Date", "Organisation", "Who replied", "Where it stands"],
          lambda r: (r["date"], r["org"], r.get("who", ""), r.get("note", "")))
    table("Meetings held", R.get("meetings"), ["Date", "Organisation", "Who", "What came of it", "Evidence"],
          lambda r: (r["date"], r["org"], r.get("who", ""), r.get("note", ""), r.get("evidence", "")))
    table("Booked, not yet held", R.get("booked"), ["When", "Organisation", "Who", "Note"],
          lambda r: (r["date"], r["org"], r.get("who", ""), r.get("note", "")))
    table("Proposals", R.get("proposals"), ["Date", "To", "What was offered", "Evidence"],
          lambda r: (r["date"], f"{r['org']} — {r.get('who', '')}", r.get("note", ""), r.get("evidence", "")))
    table("Sales", R.get("sales"), ["Committed", "Client", "Engagement", "USD", "Delivers", "Evidence"],
          lambda r: (r["date"], r["org"], r.get("what", ""), f"{r['value']:,}", r.get("deliver", ""), r.get("evidence", "")))
    table("Delivery", R.get("delivery"), ["Delivered", "Client", "Engagement", "USD", "Evidence"],
          lambda r: (r["date"], r["org"], r.get("what", ""), f"{r['value']:,}", r.get("evidence", "")))
    if q.get("excluded"):
        A(""); A("## Ruled out — not counted, not re-raised"); A("")
        for x in q["excluded"]:
            if isinstance(x, dict):   # coded form (2026-10-12): date · reason · org — note
                A(f"- {x.get('date', '')} · `{x.get('reason', '')}`" + (f" · {x['org']}" if x.get("org") else "")
                  + (f" — {x['note']}" if x.get("note") else ""))
            else:
                A(f"- {x}")
    T = q.get("threads")
    if T:
        from collections import Counter
        c = Counter(v.get("disposition") for v in T.values())
        A(""); A(f"## Thread ledger — {len(T)} Gmail threads ({c.get('counted', 0)} counted · {c.get('excluded', 0)} excluded · {c.get('pending', 0)} pending)"); A("")
        A("> What `bin/sweep_diff.py` diffs a fresh sweep against. A thread is re-read only when its message count grows.")
    if q.get("refreshes"):
        A(""); A("## Refresh history"); A("")
        A("| Date | " + " | ".join(FIELDS) + " | Note |"); A("|" + " --- |" * (len(FIELDS) + 2))
        for r in sorted(q["refreshes"], key=lambda r: r["date"], reverse=True):
            A(f"| {r['date']} | " + " | ".join(val(f, r['fields'].get(f)) for f in FIELDS) + f" | {r.get('note', '')} |")
    return "\n".join(L) + "\n"


def main():
    d = json.loads(DATA.read_text())
    today = datetime.date.today().isoformat()
    d["generated"] = datetime.datetime.now().astimezone().isoformat(timespec="minutes")
    cur = CR.current_quarter(d, today)
    bad = []

    # practice targets are the sum of cluster targets (TLBS) -- refuse to show a page where they disagree
    for q in d["quarters"]:
        for f in ("Approaches", "Meetings", "Sales"):
            cs = [c["targets"].get(f) for c in q.get("clusters", [])]
            if cs and all(v is not None for v in cs) and sum(cs) != q["targets"].get(f):
                bad.append(f"{q['id']} {f} target {q['targets'].get(f)} is not the sum of its clusters ({sum(cs)})")

    if FUNNEL.exists():
        F = json.loads(FUNNEL.read_text())
        d["funnel"], problems = funnel_view(F)
        bad += problems
        # the funnel's comparator is the campaign-era counted record; it must match this file
        through, rows = CR.read(DATA)
        if F.get("approaches", {}).get("counted") not in (None, rows["Approaches"][0]):
            bad.append(f"funnel-conversion.json was built against Approaches {F['approaches']['counted']}, "
                       f"the counted record says {rows['Approaches'][0]} — re-run funnel_conversion.py")
    else:
        d["funnel"] = None
        bad.append("funnel-conversion.json not found")

    # write the run record
    (RUNS / today).mkdir(parents=True, exist_ok=True)
    (RUNS / today / "dashboard_seed.json").write_text(json.dumps(d, indent=2) + "\n")

    # splice ONLY the data block into the page
    html = HTML.read_text()
    tag = '<script type="application/json" id="data">'
    a = html.index(tag) + len(tag)
    b = html.index("</script>", a)
    # the page never needs the thread ledger -- strip it from the copy that goes into the HTML
    page = json.loads(json.dumps(d))
    for q in page["quarters"]:
        q.pop("threads", None)
    HTML.write_text(html[:a] + "\n" + json.dumps(page, indent=2) + "\n" + html[b:])

    # the generated quarter views -- every counted quarter, not just the current one, so a
    # quarter marked final never keeps a stale view that contradicts dashboard-data.json.
    # "upcoming" blocks hold nothing yet and are skipped.
    written = []
    for q in d["quarters"]:
        if q.get("status") in ("open", "final"):
            (TLP / f"TLP-{q['id']}.md").write_text(quarter_markdown(d, q))
            written.append(q["id"])

    ct = cur.get("counted_through")
    age = (datetime.date.today() - datetime.date.fromisoformat(ct)).days if ct else None
    ab = {"Approaches": "A", "Meetings": "M", "Proposals": "P", "Sales": "S", "Delivery": "D", "Pink Sheets": "PS"}
    F6 = " · ".join(f"{ab.get(f, f)}={'—' if cur['fields'].get(f) is None else cur['fields'][f]}" for f in d["fields"])
    print(f"Dashboard: {'OK' if not bad else 'PROBLEM'} · {cur['label']} ({cur['status']}) · {F6} · views: {', '.join(written)} · "
          f"counted record {('not yet counted' if age is None else f'{age}d old ({ct})')}"
          + ("" if not bad else " · " + "; ".join(bad)))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
